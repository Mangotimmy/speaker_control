#!/usr/bin/env bash
# =============================================================================
#  Edifier R20 Tray Controller - Linux installer (per user)
#
#  Installs the application into a private virtualenv under
#  ~/.local/share/edifier-r20-tray and creates:
#    * ~/.local/bin/edifier-r20-tray        (launcher)
#    * ~/.local/share/applications/...      (application menu entry)
#    * ~/.config/autostart/...              (optional, start with the session)
#    * /etc/udev/rules.d/70-edifier-r20.rules (hidraw access, uses sudo)
#
#  Usage:
#    bash scripts/install_linux.sh                 install (asks about autostart)
#    bash scripts/install_linux.sh --autostart     install + enable autostart
#    bash scripts/install_linux.sh --no-autostart  install without autostart
#    bash scripts/install_linux.sh --uninstall     remove the application
#    bash scripts/install_linux.sh --uninstall --purge   also remove settings
# =============================================================================
set -euo pipefail

APP_ID="edifier-r20-tray"
APP_NAME="Edifier R20 Tray Controller"
APP_SHORT="Edifier R20"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
INSTALL_DIR="$DATA_HOME/$APP_ID"
BIN_DIR="$HOME/.local/bin"
PYTHON_BIN="${PYTHON_BIN:-python3}"
UDEV_RULE_FILE="/etc/udev/rules.d/70-edifier-r20.rules"
UDEV_RULE='SUBSYSTEM=="hidraw", ATTRS{idVendor}=="2d99", ATTRS{idProduct}=="a121", MODE="0660", TAG+="uaccess"'

SOURCE_FILES=(
    tray_app.py tray_popup.py r20_controller.py sound_reactive.py volume_sync.py
    audio_meter.py icon_generator.py config.py platform_utils.py media_keys.py run.py
)

MODE="install"
AUTOSTART="ask"
PURGE="no"

log()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
    sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

for arg in "$@"; do
    case "$arg" in
        --uninstall)     MODE="uninstall" ;;
        --autostart)     AUTOSTART="yes" ;;
        --no-autostart)  AUTOSTART="no" ;;
        --purge)         PURGE="yes" ;;
        -h|--help)       usage; exit 0 ;;
        *)               die "Unknown option: $arg (try --help)" ;;
    esac
done

# ---------------------------------------------------------------- uninstall
uninstall() {
    log "Stopping running instance"
    pkill -f "$INSTALL_DIR" 2>/dev/null || true
    pkill -f 'tray_app.py' 2>/dev/null || true

    log "Removing application files"
    rm -rf "$INSTALL_DIR"
    rm -f "$BIN_DIR/$APP_ID"
    rm -f "$DATA_HOME/applications/$APP_ID.desktop"
    rm -f "$CONFIG_HOME/autostart/$APP_ID.desktop"
    rm -rf "$DATA_HOME/icons/hicolor/256x256/apps/$APP_ID.png"

    if [ "$PURGE" = "yes" ]; then
        log "Removing user settings"
        rm -rf "$CONFIG_HOME/$APP_ID"
    else
        warn "User settings kept in $CONFIG_HOME/$APP_ID (use --purge to remove)"
    fi

    if [ -f "$UDEV_RULE_FILE" ]; then
        warn "The udev rule $UDEV_RULE_FILE is system wide; remove it with:"
        warn "  sudo rm $UDEV_RULE_FILE && sudo udevadm control --reload-rules"
    fi
    log "Uninstalled $APP_NAME"
}

# ----------------------------------------------------------------- install
install_app() {
    command -v "$PYTHON_BIN" >/dev/null 2>&1 || die "python3 not found. Install Python 3.10+ first."
    "$PYTHON_BIN" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' \
        || die "Python 3.10 or newer is required."

    [ -f "$ROOT/tray_app.py" ] || die "Run this script from the project checkout (tray_app.py missing)."

    log "Installing application files into $INSTALL_DIR"
    mkdir -p "$INSTALL_DIR"
    for file in "${SOURCE_FILES[@]}"; do
        cp "$ROOT/$file" "$INSTALL_DIR/"
    done

    log "Creating private virtualenv and installing dependencies"
    "$PYTHON_BIN" -m venv "$INSTALL_DIR/venv"
    "$INSTALL_DIR/venv/bin/pip" install --quiet --upgrade pip setuptools wheel
    "$INSTALL_DIR/venv/bin/pip" install --quiet -r "$ROOT/requirements-linux.txt"

    log "Installing application icon"
    if [ ! -f "$ROOT/packaging/app.png" ] && [ -f "$ROOT/packaging/make_icon.py" ]; then
        "$INSTALL_DIR/venv/bin/python" "$ROOT/packaging/make_icon.py" >/dev/null 2>&1 \
            || warn "Could not render the icon (continuing without it)"
    fi
    mkdir -p "$DATA_HOME/icons/hicolor/256x256/apps"
    if [ -f "$ROOT/packaging/app.png" ]; then
        cp "$ROOT/packaging/app.png" "$DATA_HOME/icons/hicolor/256x256/apps/$APP_ID.png"
    fi

    log "Creating launcher $BIN_DIR/$APP_ID"
    mkdir -p "$BIN_DIR"
    cat > "$BIN_DIR/$APP_ID" <<EOF
#!/usr/bin/env sh
# Edifier R20 Tray Controller launcher (generated by install_linux.sh)
exec "$INSTALL_DIR/venv/bin/python" "$INSTALL_DIR/run.py" "\$@"
EOF
    chmod +x "$BIN_DIR/$APP_ID"

    log "Creating application menu entry"
    mkdir -p "$DATA_HOME/applications"
    cat > "$DATA_HOME/applications/$APP_ID.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=$APP_SHORT
GenericName=Speaker Controller
Comment=$APP_NAME - volume, sound modes and RGB light control
Exec=$BIN_DIR/$APP_ID
Icon=$APP_ID
Terminal=false
Categories=AudioVideo;Audio;
Keywords=edifier;speaker;volume;rgb;
StartupNotify=false
EOF

    # -------------------------------------------------------- autostart
    local write_autostart=0
    case "$AUTOSTART" in
        yes) write_autostart=1 ;;
        ask)
            if [ -t 0 ]; then
                read -r -p "Start $APP_SHORT automatically when you log in? [y/N] " answer
                case "$answer" in
                    [yY]|[yY][eE][sS]) write_autostart=1 ;;
                esac
            fi
            ;;
    esac
    if [ "$write_autostart" = "1" ]; then
        mkdir -p "$CONFIG_HOME/autostart"
        cat > "$CONFIG_HOME/autostart/$APP_ID.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=$APP_SHORT
Comment=$APP_NAME
Exec=$BIN_DIR/$APP_ID
Icon=$APP_ID
Terminal=false
X-GNOME-Autostart-enabled=true
EOF
        log "Autostart enabled"
    fi

    # ------------------------------------------------------------- udev
    log "Configuring hidraw access for the Edifier R20 (VID 2d99 / PID a121)"
    if [ "$(id -u)" -eq 0 ]; then
        printf '%s\n' "$UDEV_RULE" > "$UDEV_RULE_FILE"
        udevadm control --reload-rules 2>/dev/null || true
        udevadm trigger 2>/dev/null || true
        log "udev rule installed"
    elif command -v sudo >/dev/null 2>&1; then
        if printf '%s\n' "$UDEV_RULE" | sudo tee "$UDEV_RULE_FILE" >/dev/null 2>&1; then
            sudo udevadm control --reload-rules 2>/dev/null || true
            sudo udevadm trigger 2>/dev/null || true
            log "udev rule installed"
        else
            warn "Could not install the udev rule; run manually:"
            warn "  echo '$UDEV_RULE' | sudo tee $UDEV_RULE_FILE"
            warn "  sudo udevadm control --reload-rules && sudo udevadm trigger"
        fi
    else
        warn "sudo not available. To allow the app to open the speaker, run as root:"
        warn "  echo '$UDEV_RULE' > $UDEV_RULE_FILE"
        warn "  udevadm control --reload-rules && udevadm trigger"
    fi

    # ---------------------------------------------------------- hints
    for tool in parec pactl wpctl; do
        if command -v "$tool" >/dev/null 2>&1; then
            log "Audio tool found: $tool"
        fi
    done
    if ! command -v pactl >/dev/null 2>&1 && ! command -v wpctl >/dev/null 2>&1; then
        warn "Neither pactl nor wpctl was found: system volume sync will be disabled."
        warn "Install pipewire (wpctl) or pulseaudio-utils (pactl)."
    fi
    if ! command -v parec >/dev/null 2>&1; then
        warn "parec not found: the sound-reactive rainbow falls back to speaker volume."
        warn "Install pulseaudio-utils (or pipewire-pulse)."
    fi

    log "Installed $APP_NAME"
    echo
    echo "  Start it with:  $BIN_DIR/$APP_ID"
    echo "  Or from the application menu: $APP_SHORT"
    case ":$PATH:" in
        *":$BIN_DIR:"*) ;;
        *) warn "$BIN_DIR is not in your PATH; add it to run 'edifier-r20-tray'." ;;
    esac
    echo "  Uninstall with: bash $ROOT/scripts/install_linux.sh --uninstall"
}

if [ "$MODE" = "uninstall" ]; then
    uninstall
else
    install_app
fi
