<#
.SYNOPSIS
    Builds the Windows application, its uninstaller and the setup program for
    the Edifier R20 tray controller.

.DESCRIPTION
    The installer is a self-contained PyInstaller executable (no external
    installer toolchain required):

      dist\EdifierR20Tray\EdifierR20Tray.exe            application
      build\uninstaller\Uninstall.exe                   generated uninstaller
      dist\EdifierR20Tray-Setup-<version>.exe           setup wizard

    Steps:
      1. Installs the build requirements (PyInstaller) into the chosen Python.
      2. Renders packaging\app.ico / app.png from the vector icon renderer.
      3. Writes build\version_info.txt from platform_utils.APP_VERSION.
      4. PyInstaller: application (one folder, windowed).
      5. PyInstaller: Uninstall.exe (one file, no console, no Qt).
      6. PyInstaller: setup program bundling 4 + 5.

.PARAMETER Python
    Python interpreter used for the build. Defaults to the newest interpreter
    found via the py launcher, C:\Python314\python.exe or python.exe.

.EXAMPLE
    pwsh -File packaging\build_windows.ps1
    pwsh -File packaging\build_windows.ps1 -SkipSetup
#>
[CmdletBinding()]
param(
    [string]$Python = "",
    [switch]$SkipApp,
    [switch]$SkipUninstaller,
    [switch]$SkipSetup
)

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot
$Packaging = Join-Path $Root "packaging"
$BuildDir = Join-Path $Root "build"
$DistDir = Join-Path $Root "dist"

function Write-Step([string]$Text) {
    Write-Host "==> $Text" -ForegroundColor Cyan
}

function Resolve-Python {
    param([string]$Requested)
    if ($Requested) {
        if (-not (Test-Path $Requested)) { throw "Python interpreter not found: $Requested" }
        return $Requested
    }
    $candidates = @(
        "C:\Python314\python.exe",
        "C:\Python313\python.exe",
        "C:\Python312\python.exe",
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python313\python.exe"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python312\python.exe")
    )
    foreach ($candidate in $candidates) {
        if (Test-Path $candidate) { return $candidate }
    }
    $command = Get-Command python.exe -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }
    throw "No Python interpreter found. Pass -Python <path>."
}

function Write-VersionInfo {
    param([string]$Version, [string]$Path)
    $parts = @($Version.Split('.'))
    while ($parts.Count -lt 4) { $parts += "0" }
    $four = ($parts[0..3] -join ',')
    $content = @"
# Generated by packaging/build_windows.ps1 - do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($four),
    prodvers=($four),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'Mangotimmy'),
            StringStruct('FileDescription', 'Edifier R20 Tray Controller'),
            StringStruct('FileVersion', '$Version'),
            StringStruct('InternalName', 'EdifierR20Tray'),
            StringStruct('LegalCopyright', 'Copyright (C) 2026 Mangotimmy'),
            StringStruct('OriginalFilename', 'EdifierR20Tray.exe'),
            StringStruct('ProductName', 'Edifier R20 Tray Controller'),
            StringStruct('ProductVersion', '$Version')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Path) | Out-Null
    [System.IO.File]::WriteAllText($Path, $content, (New-Object System.Text.UTF8Encoding($false)))
}

$Python = Resolve-Python -Requested $Python
Write-Step "Python: $Python"
$AppVersion = (& $Python -c "import sys; sys.path.insert(0, r'$Root'); import platform_utils; print(platform_utils.APP_VERSION)").Trim()
Write-Host "    version: $AppVersion"

Write-Step "Installing build requirements"
& $Python -m pip install --disable-pip-version-check -q -r (Join-Path $Root "requirements-dev.txt")
if ($LASTEXITCODE -ne 0) { throw "pip install failed" }

Write-Step "Generating application icon"
& $Python (Join-Path $Packaging "make_icon.py")
if ($LASTEXITCODE -ne 0) { throw "Icon generation failed" }

Write-Step "Writing version resource"
Write-VersionInfo -Version $AppVersion -Path (Join-Path $BuildDir "version_info.txt")

$PyInstaller = @(
    "-m", "PyInstaller",
    "--noconfirm", "--clean",
    "--distpath", $DistDir,
    "--workpath", (Join-Path $BuildDir "pyinstaller")
)

if (-not $SkipApp) {
    Write-Step "Building application (dist\EdifierR20Tray)"
    & $Python @PyInstaller (Join-Path $Packaging "edifier_r20_tray.spec")
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller (application) failed" }
    $appExe = Join-Path $DistDir "EdifierR20Tray\EdifierR20Tray.exe"
    if (-not (Test-Path $appExe)) { throw "Application executable missing: $appExe" }
}

if (-not $SkipUninstaller) {
    Write-Step "Building uninstaller (build\uninstaller\Uninstall.exe)"
    & $Python @PyInstaller `
        "--distpath" (Join-Path $BuildDir "uninstaller") `
        "--workpath" (Join-Path $BuildDir "pyinstaller-uninstaller") `
        (Join-Path $Packaging "uninstaller.spec")
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller (uninstaller) failed" }
    $uninstallerExe = Join-Path $BuildDir "uninstaller\Uninstall.exe"
    if (-not (Test-Path $uninstallerExe)) { throw "Uninstaller executable missing: $uninstallerExe" }
}

if (-not $SkipSetup) {
    foreach ($required in @(
        (Join-Path $DistDir "EdifierR20Tray\EdifierR20Tray.exe"),
        (Join-Path $BuildDir "uninstaller\Uninstall.exe")
    )) {
        if (-not (Test-Path $required)) {
            throw "Build the application and uninstaller first (missing $required)"
        }
    }
    Write-Step "Building setup program (dist\EdifierR20Tray-Setup-$AppVersion.exe)"
    & $Python @PyInstaller `
        "--workpath" (Join-Path $BuildDir "pyinstaller-setup") `
        (Join-Path $Packaging "installer.spec")
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller (setup) failed" }
}

Write-Step "Artifacts"
$candidates = @(
    (Join-Path $DistDir "EdifierR20Tray\EdifierR20Tray.exe"),
    (Join-Path $BuildDir "uninstaller\Uninstall.exe"),
    (Join-Path $DistDir "EdifierR20Tray-Setup-$AppVersion.exe")
)
$artifacts = @()
foreach ($path in $candidates) {
    if (Test-Path $path) {
        $item = Get-Item $path
        $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
        $artifacts += [pscustomobject]@{
            File   = $item.FullName
            SizeMB = [math]::Round($item.Length / 1MB, 1)
            SHA256 = $hash
        }
    }
}
$artifacts | Format-Table -AutoSize | Out-String | Write-Host
Write-Host "Done." -ForegroundColor Green
